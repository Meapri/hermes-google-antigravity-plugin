def _antigravity_main_patcher(_module):
    """Model picker patches (fires on hermes_cli.main import, before cmd_model).

    This must fire BEFORE select_provider_and_model is called, so the
    TUI provider list includes google-antigravity from the first run.
    """
    import antigravity_provider_patch
    ok1 = antigravity_provider_patch._patch_models_module()
    ok2 = antigravity_provider_patch._patch_model_picker()
    if not (ok1 and ok2):
        sys.stderr.write(
            "[hermes-antigravity-main] TUI picker patches skipped "
            "(API incompatibility — will still work via hermes config)\n"
        )


def _antigravity_model_switch_patcher(_module):
    """Gateway /model picker injection (fires on hermes_cli.model_switch import).

    Must fire AFTER the module body finishes so ``list_authenticated_providers``
    is defined. The providers/main hooks run while model_switch is still
    mid-import (it does ``from hermes_cli.providers import get_label``), so the
    picker wrap is deferred to this dedicated hook to avoid a circular-import
    race. ``_patch_models_module`` is re-run first (idempotent) to guarantee the
    curated Antigravity model list exists before the row is built.
    """
    import antigravity_provider_patch
    antigravity_provider_patch._patch_models_module()
    ok = antigravity_provider_patch._patch_model_switch_picker()
    if isinstance(ok, bool) and not ok:
        sys.stderr.write(
            "[hermes-antigravity-model-switch] /model picker injection skipped "
            "(API incompatibility — provider still usable via hermes config)\n"
        )


def _antigravity_runtime_provider_patcher(_module):
    """Runtime provider injection (fires on hermes_cli.runtime_provider import).

    The full apply() runs on the hermes_cli.providers import hook, but on the
    gateway startup path hermes_cli.providers can import while
    hermes_cli.runtime_provider is still mid-import — at which point
    ``resolve_runtime_provider`` is not yet defined, so _patch_runtime_provider()
    silently skips and the gateway falls back to the default provider with no
    credentials ("No inference provider configured"). This dedicated hook fires
    AFTER runtime_provider finishes loading, guaranteeing the resolver exists.
    _patch_runtime_provider() is idempotent (guarded by
    ``rp._antigravity_runtime_patched``), so re-running it here is harmless even
    if apply() already succeeded.
    """
    import antigravity_provider_patch
    ok = antigravity_provider_patch._patch_runtime_provider()
    if isinstance(ok, bool) and not ok:
        sys.stderr.write(
            "[hermes-antigravity-runtime] runtime_provider injection skipped "
            "(API incompatibility detected)\n"
        )


