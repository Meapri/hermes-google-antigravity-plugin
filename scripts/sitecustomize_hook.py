from __future__ import annotations

import os
import sys

_PATCHES_DIR = os.environ.get(
    "HERMES_PATCHES_DIR",
    os.path.expanduser("~/.hermes/patches"),
)

if os.path.isdir(_PATCHES_DIR) and _PATCHES_DIR not in sys.path:
    sys.path.insert(0, _PATCHES_DIR)


def _make_import_hook(target_module, patcher_fn, label):
    """Create a MetaPathFinder that runs patcher_fn after target_module loads."""
    try:
        from importlib.abc import MetaPathFinder
        from importlib.util import find_spec
    except ImportError:
        return

    class _Finder(MetaPathFinder):
        _patched = False

        def find_spec(self, fullname, path=None, target=None):
            if fullname != target_module or self._patched:
                return None
            if self in sys.meta_path:
                sys.meta_path.remove(self)
            try:
                spec = find_spec(fullname)
            finally:
                if self not in sys.meta_path:
                    sys.meta_path.insert(0, self)
            if spec is None or spec.loader is None:
                return None
            original_exec = getattr(spec.loader, "exec_module", None)
            if not callable(original_exec):
                return None
            finder = self

            def patched_exec(module):
                original_exec(module)
                finder._patched = True
                try:
                    result = patcher_fn(module)
                    # patcher_fn may return bool for antigravity patches
                    if isinstance(result, bool) and not result:
                        sys.stderr.write(
                            f"[{label}] patch declined "
                            f"(API incompatibility detected)\n"
                        )
                except Exception as exc:
                    import traceback
                    sys.stderr.write(
                        f"[{label}] patch failed: {type(exc).__name__}: {exc}\n"
                    )
                    traceback.print_exc(file=sys.stderr)

            spec.loader.exec_module = patched_exec
            return spec

    sys.meta_path.insert(0, _Finder())


def _load_claude_bypass():
    try:
        import anthropic_billing_bypass
    except ImportError:
        return None
    return anthropic_billing_bypass


def _claude_patcher(module):
    anthropic_billing_bypass = _load_claude_bypass()
    if anthropic_billing_bypass is None:
        return
    ok = anthropic_billing_bypass.apply_patches(module)
    if not ok:
        sys.stderr.write(
            "[hermes-claude-auth] bypass declined "
            "(API incompatibility detected)\n"
        )


def _claude_error_classifier_patcher(_module):
    """Install Claude thinking-replay error recovery as early as possible.

    ``agent.conversation_loop`` imports ``classify_api_error`` directly from
    ``agent.error_classifier``. If the classifier is imported before
    ``agent.anthropic_adapter``, the regular Claude adapter hook can be too late
    for that bound name. Patch the classifier module the moment it loads.
    """
    anthropic_billing_bypass = _load_claude_bypass()
    if anthropic_billing_bypass is None:
        return
    anthropic_billing_bypass._install_thinking_replay_classifier_patch()


